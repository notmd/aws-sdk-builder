    if functions.contains("aws.partition") {
        output.push_str(
            "            partition_resolver: &crate::endpoint_lib::DEFAULT_PARTITION_RESOLVER,\n",
        );
    }
    output.push_str("            endpoint_cache: ::arc_swap::ArcSwap::from_pointee(None),\n        }\n    }\n\n");
    render_resolve_method(output, rules, params, contexts, &functions);
