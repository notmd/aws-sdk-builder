fn render_account_id_finalize_params(output: &mut String) {
    output.push_str(
        r#"    fn finalize_params<'a>(
        &'a self,
        params: &'a mut ::aws_smithy_runtime_api::client::endpoint::EndpointResolverParams,
    ) -> ::std::result::Result<(), ::aws_smithy_runtime_api::box_error::BoxError> {
        // This is required to satisfy the borrow checker. By obtaining an `Option<Identity>`,
        // `params` is no longer mutably borrowed in the match expression below.
        // Furthermore, by using `std::mem::replace` with an empty `Identity`, we avoid
        // leaving the sensitive `Identity` inside `params` within `EndpointResolverParams`.
        let identity = params
            .get_property_mut::<::aws_smithy_runtime_api::client::identity::Identity>()
            .map(|id| {
                std::mem::replace(
                    id,
                    ::aws_smithy_runtime_api::client::identity::Identity::new(
                        (),
                        ::std::option::Option::None,
                    ),
                )
            });
        match (
            params.get_mut::<crate::config::endpoint::Params>(),
            identity
                .as_ref()
                .and_then(|id| id.property::<::aws_credential_types::attributes::AccountId>()),
        ) {
            (::std::option::Option::Some(concrete_params), ::std::option::Option::Some(account_id)) => {
                concrete_params.account_id = ::std::option::Option::Some(account_id.as_str().to_string());
            }
            (::std::option::Option::Some(_), ::std::option::Option::None) => {
                // No account ID; nothing to do.
            }
            (::std::option::Option::None, _) => {
                return ::std::result::Result::Err("service-specific endpoint params was not present".into());
            }
        }
        ::std::result::Result::Ok(())
    }
}

"#,
    );
}

fn endpoint_functions(rules: &Value) -> BTreeSet<String> {
    let mut functions = BTreeSet::new();
    collect_functions(rules, &mut functions);
    functions
}

fn collect_functions(value: &Value, functions: &mut BTreeSet<String>) {
    match value {
        Value::Object(values) => {
            if let Some(function) = values.get("fn").and_then(Value::as_str) {
                functions.insert(function.to_owned());
            }
            for value in values.values() {
                collect_functions(value, functions);
            }
        }
        Value::Array(values) => {
            for value in values {
                collect_functions(value, functions);
            }
        }
        _ => {}
    }
}

fn render_resolve_method(
    output: &mut String,
    rules: &Value,
    params: &[Param],
    contexts: &[ContextField],
    functions: &BTreeSet<String>,
) {
    let multiline_results = endpoint_results_need_multiline(rules);
    output.push_str(
        "    #[allow(\n        unused_variables,\n        unused_parens,\n        clippy::double_parens,\n        clippy::useless_conversion,\n        clippy::bool_comparison,\n        clippy::comparison_to_empty,\n        clippy::needless_borrow,\n        clippy::useless_asref,\n        clippy::redundant_closure_call,\n        clippy::clone_on_copy,\n        clippy::single_char_add_str\n    )]\n    fn resolve_endpoint<'a>(\n        &'a self,\n        params: &'a crate::config::endpoint::Params,\n    ) -> ::std::result::Result<::aws_smithy_types::endpoint::Endpoint, ::aws_smithy_runtime_api::box_error::BoxError> {\n        let mut _diagnostic_collector = crate::endpoint_lib::diagnostic::DiagnosticCollector::new();\n        #[allow(unused_mut)]\n        let mut context = ConditionContext::default();\n\n        // Param bindings\n",
    );
    for param in params {
        writeln!(
            output,
            "        let {} = &params.{};",
            param.rust, param.rust
        )
        .unwrap();
    }
    let root = rules.get("root").and_then(Value::as_i64).unwrap_or(2);
    writeln!(output, "\n        let mut current_ref: i32 = {root};\n        loop {{\n            match current_ref {{\n                ref_val if ref_val >= 100_000_000 => {{\n                    return match (ref_val - 100_000_000) as usize {{").unwrap();
    render_result_arm(
        output,
        0,
        &serde_json::json!({"type": "error", "error": "No endpoint rule matched"}),
        params,
        contexts,
        multiline_results,
    );
    if let Some(results) = rules.get("results").and_then(Value::as_array) {
        for (index, result) in results.iter().enumerate() {
            render_result_arm(
                output,
                index + 1,
                result,
                params,
                contexts,
                multiline_results,
            );
        }
    }
    output.push_str(
        "                        _ => ::std::result::Result::Err(Box::new(::aws_smithy_http::endpoint::ResolveEndpointError::message(\n                            \"No endpoint rule matched\",\n                        )) as ::aws_smithy_runtime_api::box_error::BoxError),\n                    };\n                }\n                1 | -1 => {\n                    return ::std::result::Result::Err(\n                        Box::new(::aws_smithy_http::endpoint::ResolveEndpointError::message(\"No endpoint rule matched\"))\n                            as ::aws_smithy_runtime_api::box_error::BoxError,\n                    )\n                }\n                ref_val => {\n                    let is_complement = ref_val < 0;\n                    let node = &NODES[(ref_val.unsigned_abs() as usize) - 1];\n                    let condition_result = match node.condition_index {\n",
    );
    if let Some(conditions) = rules.get("conditions").and_then(Value::as_array) {
        for (index, condition) in conditions.iter().enumerate() {
            render_condition_arm(output, index, condition, params, contexts, functions);
        }
    }
    output.push_str(
        "                        _ => unreachable!(\"Invalid condition index\"),\n                    };\n                    current_ref = if is_complement ^ condition_result { node.high_ref } else { node.low_ref };\n                }\n            }\n        }\n    }\n",
    );
}

fn endpoint_results_need_multiline(rules: &Value) -> bool {
    rules
        .get("results")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|result| result.get("endpoint"))
        .filter_map(|endpoint| endpoint.get("url"))
        .filter_map(Value::as_str)
        .any(|url| url.len() > 100)
}

fn render_result_arm(
    output: &mut String,
    index: usize,
    result: &Value,
    params: &[Param],
    contexts: &[ContextField],
    multiline: bool,
) {
    if result.get("type").and_then(Value::as_str) == Some("error") {
        let error = result
            .get("error")
            .and_then(Value::as_str)
            .unwrap_or("No endpoint rule matched");
        if error == "No endpoint rule matched" {
            writeln!(output, "                        {index} => ::std::result::Result::Err(Box::new(::aws_smithy_http::endpoint::ResolveEndpointError::message(\n                            \"{error}\",\n                        )) as ::aws_smithy_runtime_api::box_error::BoxError),").unwrap();
        } else {
            let error_value = Value::String(error.to_owned());
            let refs = expression_refs(&error_value);
            if refs.is_empty() {
                writeln!(
                    output,
                    "                        {index} => ::std::result::Result::Err(Box::new(::aws_smithy_http::endpoint::ResolveEndpointError::message(\n                            {error:?}.to_string(),\n                        )) as ::aws_smithy_runtime_api::box_error::BoxError),"
                )
                .unwrap();
                return;
            }
            writeln!(output, "                        {index} => {{").unwrap();
            for param in params {
                if refs.contains(&param.original) {
                    match param.ty {
                        ParamType::String | ParamType::StringArray => writeln!(
                            output,
                            "                            let {} = params.{}.as_deref().unwrap_or_default();",
                            param.rust,
                            param.rust
                        )
                        .unwrap(),
                        ParamType::Boolean => writeln!(
                            output,
                            "                            let {} = params.{};",
                            param.rust,
                            param.rust
                        )
                        .unwrap(),
                    }
                }
            }
            for field in contexts {
                if refs.contains(&field.original) {
                    writeln!(
                        output,
                        "                            let {} = context.{}.as_ref().expect(\"Guaranteed to have a value by earlier checks.\");",
                        field.rust,
                        field.rust
                    )
                    .unwrap();
                }
            }
            output.push_str("                            ::std::result::Result::Err(Box::new(::aws_smithy_http::endpoint::ResolveEndpointError::message(");
            render_owned_expression(output, &error_value, params, contexts);
            output.push_str(
                ")) as ::aws_smithy_runtime_api::box_error::BoxError)\n                        },\n",
            );
        }
        return;
    }
    let endpoint = result.get("endpoint").unwrap_or(&Value::Null);
    let refs = expression_refs(endpoint);
    writeln!(output, "                        {index} => {{").unwrap();
    for param in params {
        if refs.contains(&param.original) {
            match param.ty {
                ParamType::String => writeln!(output, "                            let {} = params.{}.as_deref().unwrap_or_default();", param.rust, param.rust).unwrap(),
                ParamType::Boolean => writeln!(output, "                            let {} = params.{};", param.rust, param.rust).unwrap(),
                ParamType::StringArray => writeln!(output, "                            let {} = params.{}.as_deref().unwrap_or_default();", param.rust, param.rust).unwrap(),
            }
        }
    }
    for field in contexts {
        if refs.contains(&field.original) {
            writeln!(output, "                            let {} = context.{}.as_ref().expect(\"Guaranteed to have a value by earlier checks.\");", field.rust, field.rust).unwrap();
        }
    }
    if multiline {
        output.push_str("                            ::std::result::Result::Ok(\n");
        output.push_str("                                ");
    } else {
        output.push_str("                            ::std::result::Result::Ok(");
    }
    render_owned_endpoint(output, endpoint, params, contexts);
    if multiline {
        output.push_str("\n                            )\n                        },\n");
    } else {
        output.push_str(")\n                        },\n");
    }
}

fn expression_refs(value: &Value) -> BTreeSet<String> {
    let mut refs = BTreeSet::new();
    collect_refs(value, &mut refs);
    refs
}

fn collect_refs(value: &Value, refs: &mut BTreeSet<String>) {
    match value {
        Value::String(value) => {
            let mut rest = value.as_str();
            while let Some(start) = rest.find('{') {
                let rest_after_start = &rest[start + 1..];
                let Some(end) = rest_after_start.find('}') else {
                    break;
                };
                let placeholder = &rest_after_start[..end];
                let reference = placeholder.split('#').next().unwrap_or_default();
                if !reference.is_empty() {
                    refs.insert(reference.to_owned());
                }
                rest = &rest_after_start[end + 1..];
            }
        }
        Value::Object(values) => {
            if let Some(reference) = values.get("ref").and_then(Value::as_str) {
                refs.insert(reference.to_owned());
            }
            for value in values.values() {
                collect_refs(value, refs);
            }
        }
        Value::Array(values) => {
            for value in values {
                collect_refs(value, refs);
            }
        }
        _ => {}
    }
}

fn render_condition_arm(
    output: &mut String,
    index: usize,
    condition: &Value,
    params: &[Param],
    contexts: &[ContextField],
    functions: &BTreeSet<String>,
) {
    let function = condition
        .get("fn")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let argv = condition
        .get("argv")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    let mut refs = expression_refs(condition);
    if let Some(assign) = condition.get("assign").and_then(Value::as_str) {
        refs.insert(assign.to_owned());
    }
    let trivial = function == "isSet"
        || (function == "booleanEquals"
            && argv.len() == 2
            && ((argv[0].get("ref").is_some() && argv[1].is_boolean())
                || (argv[1].get("ref").is_some() && argv[0].is_boolean()))
            && argv
                .iter()
                .filter_map(|value| value.get("ref").and_then(Value::as_str))
                .all(|name| param(params, name).is_some()));
    if trivial {
        writeln!(
            output,
            "                        {index} => {},",
            render_condition_expression(condition, params, contexts)
        )
        .unwrap();
        return;
    }
    writeln!(output, "                        {index} => (|_diagnostic_collector: &mut crate::endpoint_lib::diagnostic::DiagnosticCollector| -> bool {{").unwrap();
    for field in contexts {
        if refs.contains(&field.original) {
            let mutable =
                condition.get("assign").and_then(Value::as_str) == Some(field.original.as_str());
            writeln!(
                output,
                "                            let {} = {} context.{};",
                field.rust,
                if mutable { "&mut" } else { "&" },
                field.rust
            )
            .unwrap();
        }
    }
    if functions.contains("aws.partition") {
        output.push_str(
            "                            let partition_resolver = &self.partition_resolver;\n",
        );
    }
    let expression = render_condition_expression(condition, params, contexts);
    if function == "aws.partition" {
        let assign = condition
            .get("assign")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let target = endpoint_rust_name(assign);
        let arg = argv
            .first()
            .map(|value| {
                if value.get("fn").and_then(Value::as_str) == Some("getAttr") {
                    render_bdd_expression(value, params, contexts, false)
                } else {
                    render_function_argument(Some(value), params, contexts)
                }
            })
            .unwrap_or_default();
        write!(
            output,
            "                            {{\n                                *{target} = partition_resolver\n                                    .resolve_partition({arg}, _diagnostic_collector)\n                                    .map(|inner| inner.into());\n                                {target}.is_some()\n                            }}"
        ).unwrap();
    } else if condition.get("assign").is_some() {
        let assign = condition
            .get("assign")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let target = endpoint_rust_name(assign);
        if assignment_is_optional(condition) {
            write!(output, "                            {{\n                                *{target} = {expression}.map(|inner| inner.into());\n                                {target}.is_some()\n                            }}").unwrap();
        } else {
            write!(output, "                            {{\n                                *{target} = Some({expression}.into());\n                                true\n                            }}").unwrap();
        }
    } else {
        write!(output, "                            {expression}").unwrap();
    }
    output.push_str("\n                        })(&mut _diagnostic_collector),\n");
}

fn assignment_is_optional(condition: &Value) -> bool {
    match condition.get("fn").and_then(Value::as_str) {
        Some("parseURL") | Some("aws.parseArn") | Some("substring") | Some("split") => true,
        Some("uriEncode") => false,
        Some("getAttr") => condition
            .get("argv")
            .and_then(Value::as_array)
            .and_then(|argv| argv.get(1))
            .and_then(Value::as_str)
            .is_some_and(|path| {
                parse_attr_path(path)
                    .iter()
                    .any(|part| matches!(part, AttrPart::Index(_)))
            }),
        Some("coalesce") | Some("ite") => false,
        _ => true,
    }
}

fn render_condition_expression(
    condition: &Value,
    params: &[Param],
    contexts: &[ContextField],
) -> String {
    let function = condition
        .get("fn")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let argv = condition
        .get("argv")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    match function {
        "isSet" => argv
            .first()
            .map(|value| {
                format!(
                    "{}.is_some()",
                    render_bdd_expression(value, params, contexts, false)
                )
            })
            .unwrap_or_else(|| "false".to_owned()),
        "booleanEquals" => {
            let left = argv
                .first()
                .map(|value| render_bdd_expression(value, params, contexts, false))
                .unwrap_or_default();
            let right = argv
                .get(1)
                .map(|value| render_bdd_expression(value, params, contexts, false))
                .unwrap_or_default();
            let left_ref = argv.first().is_some_and(|value| value.get("ref").is_some());
            let right_ref = argv.get(1).is_some_and(|value| value.get("ref").is_some());
            let right = if ((!right_ref && right == "true") || (!left_ref && left == "true"))
                && (left_ref || right_ref)
            {
                "&true".to_owned()
            } else {
                right
            };
            format!("({left}) == ({right})")
        }
        "stringEquals" => {
            let left = argv
                .first()
                .map(|value| render_bdd_expression(value, params, contexts, false))
                .unwrap_or_default();
            let right = argv
                .get(1)
                .map(|value| render_bdd_expression(value, params, contexts, false))
                .unwrap_or_default();
            let left_optional = argv
                .first()
                .is_some_and(|value| is_optional_string_expression(value, params, contexts));
            let right_optional = argv
                .get(1)
                .is_some_and(|value| is_optional_string_expression(value, params, contexts));
            let left = if right_optional && !left_optional {
                format!(
                    "&mut Some(({}{}))",
                    left,
                    string_into_suffix(argv.first().expect("left argument exists"))
                )
            } else {
                left
            };
            let right = if left_optional && !right_optional {
                format!(
                    "&mut Some(({}{}))",
                    right,
                    string_into_suffix(argv.get(1).expect("right argument exists"))
                )
            } else {
                right
            };
            if left_optional || right_optional {
                format!("({left}) == {right}")
            } else {
                format!("({left}) == ({right})")
            }
        }
        _ => {
            let expression = render_bdd_function(function, &argv, params, contexts);
            if function == "getAttr"
                && condition.get("assign").is_none()
                && argv.get(1).and_then(Value::as_str).is_some_and(|path| {
                    parse_attr_path(path)
                        .iter()
                        .any(|part| matches!(part, AttrPart::Index(_)))
                })
            {
                format!("{expression}.is_some()")
            } else {
                expression
            }
        }
    }
}

fn string_into_suffix(value: &Value) -> &'static str {
    if value.get("fn").is_some() {
        ".into()"
    } else {
        ".to_string().into()"
    }
}

fn is_optional_string_expression(
    value: &Value,
    params: &[Param],
    contexts: &[ContextField],
) -> bool {
    let Some(reference) = value.get("ref").and_then(Value::as_str) else {
        return false;
    };
    param(params, reference)
        .is_some_and(|param| param.ty == ParamType::String || param.ty == ParamType::StringArray)
        || context(contexts, reference).is_some()
}

fn render_bdd_expression(
    value: &Value,
    params: &[Param],
    contexts: &[ContextField],
    owned: bool,
) -> String {
    if let Some(reference) = value.get("ref").and_then(Value::as_str) {
        let name = param(params, reference)
            .map(|param| param.rust.clone())
            .or_else(|| context(contexts, reference).map(|field| field.rust.clone()))
            .unwrap_or_else(|| endpoint_rust_name(reference));
        if owned {
            if param(params, reference).is_some_and(|param| param.ty == ParamType::Boolean) {
                return format!("*{name}");
            }
            return format!("{name}.to_owned()");
        }
        return name;
    }
    if let Some(function) = value.get("fn").and_then(Value::as_str) {
        let args = value
            .get("argv")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        let expression = render_bdd_function(function, &args, params, contexts);
        return if owned {
            format!("{expression}.to_owned()")
        } else {
            expression
        };
    }
    match value {
        Value::String(value) if value.contains('{') => {
            render_condition_template(value, params, contexts, owned)
        }
        Value::String(value) => format!("{value:?}"),
        Value::Bool(value) => value.to_string(),
        Value::Number(value) => value.to_string(),
        Value::Array(values) => format!(
            "vec![{}]",
            values
                .iter()
                .map(|value| render_bdd_expression(value, params, contexts, owned))
                .collect::<Vec<_>>()
                .join(",")
        ),
        Value::Object(values) => {
            if values.len() == 1 && values.contains_key("ref") {
                unreachable!()
            }
            "::std::default::Default::default()".to_owned()
        }
        Value::Null => "()".to_owned(),
    }
}

fn render_condition_template(
    template: &str,
    params: &[Param],
    contexts: &[ContextField],
    owned: bool,
) -> String {
    let placeholders = template.match_indices('{').collect::<Vec<_>>();
    if placeholders.len() == 1
        && placeholders[0].0 == 0
        && let Some(end) = template.find('}')
        && end + 1 == template.len()
    {
        let value = parse_template_value(&template[1..end]);
        return if owned {
            render_bdd_expression(&value, params, contexts, true)
        } else {
            render_condition_template_piece(&value, params, contexts)
        };
    }

    let mut output = String::new();
    if !owned {
        output.push('&');
    }
    output.push_str("{ let mut out = String::new();");
    let mut cursor = 0;
    for (start, _) in placeholders {
        let Some(relative_end) = template[start..].find('}') else {
            break;
        };
        let end = start + relative_end;
        if start > cursor {
            write!(output, " out.push_str({:?});", &template[cursor..start]).unwrap();
        }
        write!(
            output,
            " out.push_str(&{});",
            render_condition_template_piece(
                &parse_template_value(&template[start + 1..end]),
                params,
                contexts,
            )
        )
        .unwrap();
        cursor = end + 1;
    }
    if cursor < template.len() {
        write!(output, " out.push_str({:?});", &template[cursor..]).unwrap();
    }
    output.push_str(" out }");
    output
}

fn render_condition_template_piece(
    value: &Value,
    params: &[Param],
    contexts: &[ContextField],
) -> String {
    if let Some(reference) = value.get("ref").and_then(Value::as_str) {
        let expression = render_bdd_expression(value, params, contexts, false);
        if let Some(param) = param(params, reference) {
            return match param.ty {
                ParamType::String | ParamType::StringArray => {
                    format!("{expression}.as_deref().unwrap_or_default()")
                }
                ParamType::Boolean => expression,
            };
        }
        if let Some(field) = context(contexts, reference) {
            return match field.ty {
                ContextType::String | ContextType::BorrowedString => {
                    format!("{expression}.as_deref().unwrap_or_default()")
                }
                _ => expression,
            };
        }
        return format!("{expression}.as_ref()");
    }
    if value.get("fn").and_then(Value::as_str) == Some("getAttr") {
        return render_get_attr(
            value
                .get("argv")
                .and_then(Value::as_array)
                .and_then(|argv| argv.first()),
            value
                .get("argv")
                .and_then(Value::as_array)
                .and_then(|argv| argv.get(1)),
            params,
            contexts,
        );
    }
    render_bdd_expression(value, params, contexts, false)
}

fn render_bdd_function(
    function: &str,
    argv: &[Value],
    params: &[Param],
    contexts: &[ContextField],
) -> String {
    let args = argv
        .iter()
        .map(|value| render_bdd_expression(value, params, contexts, false))
        .collect::<Vec<_>>();
    match function {
        "getAttr" => render_get_attr(argv.first(), argv.get(1), params, contexts),
        "aws.partition" => "partition_result".to_owned(),
        "parseURL" => format!(
            "crate::endpoint_lib::parse_url::parse_url({}, _diagnostic_collector)",
            render_function_argument(argv.first(), params, contexts)
        ),
        "aws.parseArn" => format!(
            "crate::endpoint_lib::arn::parse_arn({}, _diagnostic_collector)",
            render_function_argument(argv.first(), params, contexts)
        ),
        "isValidHostLabel" => format!(
            "crate::endpoint_lib::host::is_valid_host_label({}, {}, _diagnostic_collector)",
            render_function_argument(argv.first(), params, contexts),
            args.get(1).cloned().unwrap_or_else(|| "true".to_owned())
        ),
        "coalesce" => format!(
            "crate::endpoint_lib::coalesce::coalesce!({})",
            argv.iter()
                .map(|value| render_coalesce_argument(value, params, contexts))
                .collect::<Vec<_>>()
                .join(",")
        ),
        "ite" => format!(
            "crate::endpoint_lib::ite::ite!({})",
            argv.iter()
                .map(|value| render_ite_argument(value, params, contexts))
                .collect::<Vec<_>>()
                .join(",")
        ),
        "substring" => format!(
            "crate::endpoint_lib::substring::substring({}, _diagnostic_collector)",
            argv.iter()
                .map(|value| render_function_argument(Some(value), params, contexts))
                .collect::<Vec<_>>()
                .join(",")
        ),
        "split" => format!(
            "crate::endpoint_lib::split::split({}, _diagnostic_collector)",
            argv.iter()
                .map(|value| render_function_argument(Some(value), params, contexts))
                .collect::<Vec<_>>()
                .join(",")
        ),
        "uriEncode" => format!(
            "crate::endpoint_lib::uri_encode::uri_encode({}, _diagnostic_collector)",
            render_function_argument(argv.first(), params, contexts)
        ),
        "aws.isVirtualHostableS3Bucket" => format!(
            "crate::endpoint_lib::s3::is_virtual_hostable_s3_bucket({}, {}, _diagnostic_collector)",
            render_function_argument(argv.first(), params, contexts),
            args.get(1).cloned().unwrap_or_else(|| "false".to_owned())
        ),
        _ => format!("{}({})", endpoint_rust_name(function), args.join(",")),
    }
}

fn render_function_argument(
    value: Option<&Value>,
    params: &[Param],
    contexts: &[ContextField],
) -> String {
    let Some(value) = value else {
        return String::new();
    };
    let Some(reference) = value.get("ref").and_then(Value::as_str) else {
        return render_bdd_expression(value, params, contexts, false);
    };
    let expression = render_bdd_expression(value, params, contexts, false);
    let optional = param(params, reference).is_some_and(|param| param.ty != ParamType::Boolean)
        || context(contexts, reference).is_some();
    if optional {
        format!("if let Some(param) = {expression} {{ param }} else {{ return false }}")
    } else {
        expression
    }
}

fn render_coalesce_argument(value: &Value, params: &[Param], contexts: &[ContextField]) -> String {
    if let Some(function) = value.get("fn").and_then(Value::as_str)
        && matches!(
            function,
            "parseURL" | "aws.parseArn" | "substring" | "getAttr"
        )
    {
        return format!(
            "if let Some(inner) = {} {{ inner }} else {{ return false }}",
            render_bdd_function(
                function,
                value
                    .get("argv")
                    .and_then(Value::as_array)
                    .map(Vec::as_slice)
                    .unwrap_or_default(),
                params,
                contexts,
            )
        );
    }
    let expression = render_bdd_expression(value, params, contexts, false);
    if value
        .get("ref")
        .and_then(Value::as_str)
        .is_some_and(|reference| {
            param(params, reference).is_some_and(|param| !param.required)
                || context(contexts, reference).is_some()
        })
    {
        format!("{expression}.clone()")
    } else if matches!(value, Value::String(_)) {
        format!("{expression}.to_string()")
    } else {
        expression
    }
}

fn render_ite_argument(value: &Value, params: &[Param], contexts: &[ContextField]) -> String {
    let expression = render_bdd_expression(value, params, contexts, false);
    if matches!(value, Value::String(_)) {
        format!("{expression}.to_string()")
    } else if let Some(reference) = value.get("ref").and_then(Value::as_str) {
        let optional = param(params, reference).is_some_and(|param| param.ty != ParamType::Boolean)
            || context(contexts, reference).is_some();
        if optional {
            format!("{expression}.clone().expect(\"Reference already confirmed Some\")")
        } else {
            expression
        }
    } else {
        expression
    }
}

fn render_get_attr(
    target: Option<&Value>,
    path: Option<&Value>,
    params: &[Param],
    contexts: &[ContextField],
) -> String {
    let target_ref = target
        .and_then(|value| value.get("ref"))
        .and_then(Value::as_str);
    let target = target
        .map(|value| render_bdd_expression(value, params, contexts, false))
        .unwrap_or_default();
    let mut expression = String::new();
    let path = path.and_then(Value::as_str).unwrap_or_default();
    let parts = parse_attr_path(path);
    for part in &parts {
        match part {
            AttrPart::Key(key) => {
                expression.push('.');
                expression.push_str(&endpoint_rust_name(key));
                expression.push_str("()");
            }
            AttrPart::Index(index) => {
                if *index == 0 {
                    expression.push_str(".first().cloned()");
                } else if *index < 0 {
                    write!(expression, ".iter().nth_back({}).cloned()", -index - 1).unwrap();
                } else {
                    write!(expression, ".get({index}).cloned()").unwrap();
                }
            }
        }
    }
    if let Some(reference) = target_ref {
        let optional = param(params, reference).is_some_and(|param| param.ty != ParamType::Boolean)
            || context(contexts, reference).is_some();
        if optional {
            return format!(
                "if let Some(inner) = {target} {{ inner{expression} }} else {{ return false }}"
            );
        }
    }
    format!("{target}{expression}")
}

#[derive(Debug)]
enum AttrPart {
    Key(String),
    Index(i32),
}

fn parse_attr_path(path: &str) -> Vec<AttrPart> {
    let mut parts = Vec::new();
    let mut rest = path;
    while !rest.is_empty() {
        if let Some(start) = rest.find('[') {
            if start > 0 {
                parts.push(AttrPart::Key(rest[..start].to_owned()));
            }
            let end = rest[start + 1..]
                .find(']')
                .map(|end| end + start + 1)
                .unwrap_or(rest.len() - 1);
            if let Ok(index) = rest[start + 1..end].parse() {
                parts.push(AttrPart::Index(index));
            }
            rest = rest.get(end + 1..).unwrap_or_default();
        } else {
            parts.push(AttrPart::Key(rest.to_owned()));
            break;
        }
    }
    parts
}

fn render_owned_endpoint(
    output: &mut String,
    endpoint: &Value,
    params: &[Param],
    contexts: &[ContextField],
) {
    output.push_str("::aws_smithy_types::endpoint::Endpoint::builder()");
    if let Some(url) = endpoint.get("url") {
        output.push_str(".url(");
        render_owned_url(output, url, params, contexts);
        output.push(')');
    }
    if let Some(headers) = endpoint.get("headers").and_then(Value::as_object) {
        for (name, values) in headers {
            if let Some(values) = values.as_array() {
                for value in values {
                    write!(output, ".header({name:?}, ").unwrap();
                    render_owned_expression(output, value, params, contexts);
                    output.push(')');
                }
            }
        }
    }
    if let Some(properties) = endpoint.get("properties").and_then(Value::as_object) {
        for (name, value) in properties {
            if name == "authSchemes" {
                if let Some(schemes) = value.as_array() {
                    for scheme in schemes {
                        let Some(scheme) = scheme.as_object() else {
                            continue;
                        };
                        let scheme_name = scheme
                            .get("name")
                            .cloned()
                            .unwrap_or(Value::String("unknown".to_owned()));
                        let members = scheme
                            .iter()
                            .filter(|(key, _)| key.as_str() != "name")
                            .collect::<Vec<_>>();
                        write!(output, ".auth_scheme(\n                                ::aws_smithy_types::endpoint::EndpointAuthScheme::with_capacity(").unwrap();
                        render_owned_expression(output, &scheme_name, params, contexts);
                        writeln!(output, ", {})", members.len()).unwrap();
                        let mut members = members;
                        members.sort_by(|left, right| left.0.cmp(right.0));
                        for (key, value) in members {
                            write!(output, "                                    .put({key:?}, ")
                                .unwrap();
                            render_auth_scheme_value(output, value, params, contexts);
                            output.push_str(")\n");
                        }
                        output.push_str("                            )");
                    }
                }
            } else {
                write!(output, ".property({name:?}, ").unwrap();
                render_owned_expression(output, value, params, contexts);
                output.push(')');
            }
        }
    }
    output.push_str(".build()");
}

fn render_auth_scheme_value(
    output: &mut String,
    value: &Value,
    params: &[Param],
    contexts: &[ContextField],
) {
    if let Some(template) = value.as_str() {
        if !template.contains('{') {
            write!(output, "{template:?}").unwrap();
            return;
        }

        let placeholders = template.match_indices('{').collect::<Vec<_>>();
        if placeholders.len() == 1
            && placeholders[0].0 == 0
            && let Some(end) = template.find('}')
            && end + 1 == template.len()
        {
            render_template_expression(output, &template[1..end], params, contexts);
            return;
        }

        output.push_str("&{\n                                    let mut out = String::new();\n");
        let mut cursor = 0;
        for (start, _) in placeholders {
            let Some(relative_end) = template[start..].find('}') else {
                break;
            };
            let end = start + relative_end;
            if start > cursor {
                writeln!(
                    output,
                    "                                    out.push_str({:?});",
                    &template[cursor..start]
                )
                .unwrap();
            }
            output.push_str("                                    out.push_str(&");
            render_template_expression(output, &template[start + 1..end], params, contexts);
            output.push_str(");\n");
            cursor = end + 1;
        }
        if cursor < template.len() {
            writeln!(
                output,
                "                                    out.push_str({:?});",
                &template[cursor..]
            )
            .unwrap();
        }
        output
            .push_str("                                    out\n                                }");
        return;
    }

    render_owned_expression(output, value, params, contexts);
}

fn render_owned_url(
    output: &mut String,
    value: &Value,
    params: &[Param],
    contexts: &[ContextField],
) {
    if let Some(reference) = value.get("ref").and_then(Value::as_str) {
        let name = endpoint_rust_name(reference);
        write!(output, "{name}.to_owned()").unwrap();
        return;
    }
    let Some(template) = value.as_str() else {
        render_owned_expression(output, value, params, contexts);
        return;
    };
    let placeholders = template.match_indices('{').collect::<Vec<_>>();
    if placeholders.is_empty() {
        write!(output, "{template:?}.to_string()").unwrap();
        return;
    }
    output.push_str("{\n                                        let mut out = String::new();\n");
    let mut cursor = 0;
    for (start, _) in placeholders {
        let Some(end) = template[start..].find('}') else {
            break;
        };
        let end = start + end;
        if start > cursor {
            writeln!(
                output,
                "                                        out.push_str({:?});",
                &template[cursor..start]
            )
            .unwrap();
        }
        output.push_str("                                        #[allow(clippy::needless_borrow)]\n                                        out.push_str(&");
        render_template_expression(output, &template[start + 1..end], params, contexts);
        output.push_str(");\n");
        cursor = end + 1;
    }
    if cursor < template.len() {
        writeln!(
            output,
            "                                        out.push_str({:?});",
            &template[cursor..]
        )
        .unwrap();
    }
    output.push_str(
        "                                        out\n                                    }",
    );
}

fn render_template_expression(
    output: &mut String,
    value: &str,
    params: &[Param],
    contexts: &[ContextField],
) {
    let value = parse_template_value(value);
    if value.get("fn").and_then(Value::as_str) == Some("getAttr")
        && let Some(target) = value
            .get("argv")
            .and_then(Value::as_array)
            .and_then(|argv| argv.first())
            .and_then(|target| target.get("ref"))
            .and_then(Value::as_str)
            .and_then(|name| context(contexts, name))
    {
        output.push_str(&target.rust);
        for part in parse_attr_path(
            value
                .get("argv")
                .and_then(Value::as_array)
                .and_then(|argv| argv.get(1))
                .and_then(Value::as_str)
                .unwrap_or_default(),
        ) {
            match part {
                AttrPart::Key(key) => {
                    write!(output, ".{}()", endpoint_rust_name(&key)).unwrap();
                }
                AttrPart::Index(index) => {
                    if index == 0 {
                        output.push_str(".first().cloned()");
                    } else if index < 0 {
                        write!(output, ".iter().nth_back({}).cloned()", -index - 1).unwrap();
                    } else {
                        write!(output, ".get({index}).cloned()").unwrap();
                    }
                }
            }
        }
        return;
    }
    let expression = render_bdd_expression(&value, params, contexts, false);
    if let Some(reference) = value.get("ref").and_then(Value::as_str) {
        if let Some(field) = context(contexts, reference) {
            if field.ty == ContextType::Partition
                || field.ty == ContextType::Arn
                || field.ty == ContextType::Url
            {
                output.push_str(&expression);
            } else {
                output.push_str(&format!("{expression}.as_ref()"));
            }
        } else {
            output.push_str(&format!("{expression}.as_ref()"));
        }
    } else if let Some(function) = value.get("fn").and_then(Value::as_str) {
        let expression = render_bdd_function(
            function,
            value
                .get("argv")
                .and_then(Value::as_array)
                .map(Vec::as_slice)
                .unwrap_or_default(),
            params,
            contexts,
        );
        output.push_str(&expression);
    } else {
        output.push_str(&expression);
    }
}

fn parse_template_value(value: &str) -> Value {
    if let Some((target, path)) = value.split_once('#') {
        let mut object = serde_json::Map::new();
        object.insert("fn".to_owned(), Value::String("getAttr".to_owned()));
        object.insert(
            "argv".to_owned(),
            Value::Array(vec![
                serde_json::json!({"ref": target}),
                Value::String(path.to_owned()),
            ]),
        );
        return Value::Object(object);
    }
    serde_json::json!({"ref": value})
}

fn render_owned_expression(
    output: &mut String,
    value: &Value,
    params: &[Param],
    contexts: &[ContextField],
) {
    if value.get("ref").is_some() {
        let expression = render_bdd_expression(value, params, contexts, true);
        output.push_str(&expression);
        return;
    }
    if let Some(function) = value.get("fn").and_then(Value::as_str) {
        let args = value
            .get("argv")
            .and_then(Value::as_array)
            .map(Vec::as_slice)
            .unwrap_or_default();
        if function == "getAttr" {
            let expression = render_bdd_function(function, args, params, contexts);
            write!(output, "{expression}.to_owned()").unwrap();
        } else {
            write!(
                output,
                "{expression}.to_owned()",
                expression = render_bdd_function(function, args, params, contexts)
            )
            .unwrap();
        }
        return;
    }
    match value {
        Value::String(value) if value.contains('{') => {
            render_owned_template(output, value, params, contexts);
        }
        Value::String(value) => write!(output, "{value:?}.to_string()").unwrap(),
        Value::Bool(value) => write!(output, "{value}").unwrap(),
        Value::Number(value) => write!(output, "{value}").unwrap(),
        Value::Array(values) => {
            output.push_str("vec![");
            for (index, value) in values.iter().enumerate() {
                output.push_str("::aws_smithy_types::Document::from(");
                render_owned_expression(output, value, params, contexts);
                output.push(')');
                if index + 1 < values.len() {
                    output.push(',');
                }
            }
            output.push(']');
        }
        Value::Object(values) => {
            output.push_str("{ let mut out = ::std::collections::HashMap::new();");
            for (key, value) in values {
                write!(output, " out.insert({key:?}.to_string(), ").unwrap();
                render_owned_expression(output, value, params, contexts);
                output.push_str(".into());");
            }
            output.push_str(" out }");
        }
        Value::Null => output.push_str("::aws_smithy_types::Document::Null"),
    }
}

fn render_owned_template(
    output: &mut String,
    template: &str,
    params: &[Param],
    contexts: &[ContextField],
) {
    let placeholders = template.match_indices('{').collect::<Vec<_>>();
    if placeholders.len() == 1
        && placeholders[0].0 == 0
        && let Some(end) = template.find('}')
        && end + 1 == template.len()
    {
        let expression = parse_template_value(&template[1..end]);
        render_owned_expression(output, &expression, params, contexts);
        return;
    }
    render_owned_url(
        output,
        &Value::String(template.to_owned()),
        params,
        contexts,
    );
}

fn render_nodes(output: &mut String, rules: &Value) {
    let nodes = rules
        .get("nodes")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let bytes = decode_base64(nodes);
    let count = bytes.len() / 12;
    writeln!(
        output,
        "const NODES: [crate::endpoint_lib::bdd_interpreter::BddNode; {count}] = ["
    )
    .unwrap();
    for index in 0..count {
        let offset = index * 12;
        let condition = read_i32(&bytes[offset..offset + 4]);
        let high = read_i32(&bytes[offset + 4..offset + 8]);
        let low = read_i32(&bytes[offset + 8..offset + 12]);
        writeln!(output, "    crate::endpoint_lib::bdd_interpreter::BddNode {{\n        condition_index: {condition},\n        high_ref: {high},\n        low_ref: {low},\n    }},").unwrap();
    }
    output.push_str("];\n");
}

fn decode_base64(value: &str) -> Vec<u8> {
    let mut output = Vec::new();
    let mut buffer = 0u32;
    let mut bits = 0u8;
    for byte in value.bytes() {
        let Some(value) = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
            .bytes()
            .position(|candidate| candidate == byte)
        else {
            continue;
        };
        buffer = (buffer << 6) | value as u32;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            output.push((buffer >> bits) as u8);
            buffer &= (1 << bits) - 1;
        }
    }
    output
}

fn read_i32(bytes: &[u8]) -> i32 {
    i32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]])
}

fn render_context(output: &mut String, contexts: &[ContextField]) {
    output.push_str(
        "// These are all optional since they are set by conditions and will\n\
         // all be unset when we start evaluation\n\
         #[derive(Default)]\n\
         #[allow(unused_lifetimes)]\n\
         pub(crate) struct ConditionContext<'a> {\n",
    );
    for field in contexts {
        let ty = match field.ty {
            ContextType::Partition => {
                "Option<crate::endpoint_lib::partition::Partition<'a>>".to_owned()
            }
            ContextType::Url => "Option<crate::endpoint_lib::parse_url::Url<'a>>".to_owned(),
            ContextType::Arn => "Option<crate::endpoint_lib::arn::Arn<'a>>".to_owned(),
            ContextType::BorrowedString => "Option<&'a str>".to_owned(),
            ContextType::String => "Option<::std::string::String>".to_owned(),
            ContextType::QualifiedString => {
                "::std::option::Option<::std::string::String>".to_owned()
            }
        };
        writeln!(output, "    pub(crate) {}: {ty},", field.rust).unwrap();
    }
    output.push_str(
        "    // Sometimes none of the members reference the lifetime, this makes it still valid\n\
             phantom: std::marker::PhantomData<&'a ()>,\n\
         }\n\n",
    );
}

fn render_params(output: &mut String, params: &[Param], validate_region: bool) {
    output.push_str(
        "#[non_exhaustive]\n\
         #[derive(::std::clone::Clone, ::std::cmp::PartialEq, ::std::fmt::Debug)]\n\
         /// Configuration parameters for resolving the correct endpoint\n\
         pub struct Params {\n",
    );
    for param in params {
        if let Some(documentation) = &param.documentation {
            writeln!(output, "    /// {documentation}").unwrap();
        }
        writeln!(
            output,
            "    pub(crate) {}: {},",
            param.rust,
            param_field_type(param)
        )
        .unwrap();
    }
    output.push_str("}\nimpl Params {\n    /// Create a builder for [`Params`]\n    pub fn builder() -> crate::config::endpoint::ParamsBuilder {\n        crate::config::endpoint::ParamsBuilder::default()\n    }\n");
    for param in params {
        if let Some(documentation) = &param.documentation {
            writeln!(output, "    /// {documentation}").unwrap();
        } else {
            writeln!(output, "    /// Gets the value for `{}`", param.rust).unwrap();
        }
        writeln!(
            output,
            "    pub fn {}(&self) -> {} {{",
            param.rust,
            param_getter_type(param)
        )
        .unwrap();
        match param.ty {
            ParamType::String => {
                output.push_str(&format!("        self.{}.as_deref()\n", param.rust))
            }
            ParamType::Boolean => {
                if param.required {
                    output.push_str(&format!("        Some(self.{})\n", param.rust));
                } else {
                    output.push_str(&format!("        self.{}\n", param.rust));
                }
            }
            ParamType::StringArray => {
                output.push_str(&format!("        self.{}.as_deref()\n", param.rust))
            }
        }
        output.push_str("    }\n");
    }
    output.push_str("}\n\n/// Builder for [`Params`]\n#[derive(::std::clone::Clone, ::std::cmp::PartialEq, ::std::default::Default, ::std::fmt::Debug)]\npub struct ParamsBuilder {\n");
    for param in params {
        writeln!(
            output,
            "    {}: ::std::option::Option<{}>,",
            param.rust,
            param_value_type(param)
        )
        .unwrap();
    }
    output.push_str("}\nimpl ParamsBuilder {\n    /// Consume this builder, creating [`Params`].\n    pub fn build(self) -> ::std::result::Result<crate::config::endpoint::Params, crate::config::endpoint::InvalidParams> {\n");
    if validate_region && params.iter().any(|param| param.original == "Region") {
        output.push_str("        if let Some(region) = &self.region {\n            if !crate::endpoint_lib::host::is_valid_host_label(\n                region.as_ref() as &str,\n                true,\n                &mut crate::endpoint_lib::diagnostic::DiagnosticCollector::new(),\n            ) {\n                return Err(crate::config::endpoint::InvalidParams::invalid_value(\n                    \"region\",\n                    \"must be a valid host label\",\n                ));\n            }\n        };\n");
    }
    output.push_str("        Ok(\n            #[allow(clippy::unnecessary_lazy_evaluations)]\n            crate::config::endpoint::Params {\n");
    for param in params {
        write!(
            output,
            "                {}: self.{}",
            param.rust, param.rust
        )
        .unwrap();
        if let Some(default) = &param.default {
            write!(
                output,
                ".or_else(|| Some({}))",
                render_default_value(default)
            )
            .unwrap();
        }
        if param.required {
            write!(
                output,
                ".ok_or_else(|| crate::config::endpoint::InvalidParams::missing({:?}))?",
                param.rust
            )
            .unwrap();
        }
        output.push_str(",\n");
    }
    output.push_str("            },\n        )\n    }\n");
    for param in params {
        render_setter_docs(output, param);
        writeln!(
            output,
            "    pub fn {}(mut self, value: impl Into<{}>) -> Self {{",
            param.rust,
            param_value_type(param)
        )
        .unwrap();
        writeln!(
            output,
            "        self.{} = Some(value.into());\n        self\n    }}\n",
            param.rust
        )
        .unwrap();
        render_setter_docs(output, param);
        writeln!(output, "    pub fn set_{}(mut self, param: Option<{}>) -> Self {{\n        self.{} = param;\n        self\n    }}", param.rust, param_value_type(param), param.rust).unwrap();
    }
    output.push_str("}\n\n");
    output.push_str(
        "/// An error that occurred during endpoint resolution\n\
         #[derive(Debug)]\n\
         pub struct InvalidParams {\n\
             field: std::borrow::Cow<'static, str>,\n\
             kind: InvalidParamsErrorKind,\n\
         }\n\n\
         /// The kind of invalid parameter error\n\
         #[derive(Debug)]\n\
         enum InvalidParamsErrorKind {\n\
             MissingField,\n\
             InvalidValue { message: &'static str },\n\
         }\n\n\
         impl InvalidParams {\n\
             #[allow(dead_code)]\n\
             fn missing(field: &'static str) -> Self {\n\
                 Self {\n\
                     field: field.into(),\n\
                     kind: InvalidParamsErrorKind::MissingField,\n\
                 }\n\
             }\n\n\
             #[allow(dead_code)]\n\
             fn invalid_value(field: &'static str, message: &'static str) -> Self {\n\
                 Self {\n\
                     field: field.into(),\n\
                     kind: InvalidParamsErrorKind::InvalidValue { message },\n\
                 }\n\
             }\n\
         }\n\n\
         impl std::fmt::Display for InvalidParams {\n\
             fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n\
                 match self.kind {\n\
                     InvalidParamsErrorKind::MissingField => write!(f, \"a required field was missing: `{}`\", self.field),\n\
                     InvalidParamsErrorKind::InvalidValue { message } => write!(f, \"invalid value for field: `{}` - {}\", self.field, message),\n\
                 }\n\
             }\n\
         }\n\n\
         impl std::error::Error for InvalidParams {}\n",
    );
}

fn render_setter_docs(output: &mut String, param: &Param) {
    writeln!(output, "    /// Sets the value for {}", param.rust).unwrap();
    if param.default.is_some() || param.documentation.is_some() {
        output.push_str("    ///\n");
    }
    if let Some(default) = &param.default {
        writeln!(
            output,
            "    /// When unset, this parameter has a default value of `{}`.",
            render_default_doc(default)
        )
        .unwrap();
    }
    if let Some(documentation) = &param.documentation {
        writeln!(output, "    /// {documentation}").unwrap();
    }
}

fn param_value_type(param: &Param) -> String {
    match param.ty {
        ParamType::String => "::std::string::String".to_owned(),
        ParamType::Boolean => "bool".to_owned(),
        ParamType::StringArray => "::std::vec::Vec<::std::string::String>".to_owned(),
    }
}

fn param_field_type(param: &Param) -> String {
    if param.required {
        match param.ty {
            ParamType::String => "::std::option::Option<::std::string::String>".to_owned(),
            ParamType::Boolean => "bool".to_owned(),
            ParamType::StringArray => {
                "::std::option::Option<::std::vec::Vec<::std::string::String>>".to_owned()
            }
        }
    } else {
        format!("::std::option::Option<{}>", param_value_type(param))
    }
}

fn param_getter_type(param: &Param) -> String {
    match param.ty {
        ParamType::String => "::std::option::Option<&str>".to_owned(),
        ParamType::Boolean => "::std::option::Option<bool>".to_owned(),
        ParamType::StringArray => "::std::option::Option<&[::std::string::String]>".to_owned(),
    }
}

fn render_default_value(value: &Value) -> String {
    match value {
        Value::Bool(value) => value.to_string(),
        Value::String(value) => format!("{value:?}.to_string()"),
        Value::Array(values) => format!(
            "vec![{}]",
            values
                .iter()
                .map(render_default_value)
                .collect::<Vec<_>>()
                .join(",")
        ),
        _ => "::std::default::Default::default()".to_owned(),
    }
}

fn render_default_doc(value: &Value) -> String {
    match value {
        Value::Bool(value) => value.to_string(),
        Value::String(value) => value.clone(),
        Value::Array(values) => format!(
            "[{}]",
            values
                .iter()
                .map(render_default_doc)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        _ => value.to_string(),
    }
}
